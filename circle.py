import math


def area(r):
    '''
    Принимает радиус окружности r, возвращает её площадь (π * r^2).
    Пример вызова: area(3) -> 28.274333882308138
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает радиус окружности r, возвращает длину окружности (2 * π * r).
    Пример вызова: perimeter(3) -> 18.84955592153876
    '''
    return 2 * math.pi * r