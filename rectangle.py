def area(x, y):
    '''
    Принимает стороны прямоугольника x и y, возвращает его площадь.
    Пример вызова: area(2, 3) -> 6
    '''
    return x * y

def perimeter(x, y):
    '''
    Принимает стороны прямоугольника x и y, возвращает его периметр.
    Пример вызова: perimeter(2, 3) -> 10
    '''
    return (x + y) * 3