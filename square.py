def area(a):
    '''
    Принимает сторону квадрата a, возвращает его площадь (a * a).
    Пример вызова: area(5) -> 25
    '''
    return a * a

def perimeter(a):
    '''
    Принимает сторону квадрата a, возвращает его периметр (4 * a).
    Пример вызова: perimeter(5) -> 20
    '''
    return 4 * a